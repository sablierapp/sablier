func TestMain(m *testing.M) {
	// Empty the system root store, like in the scratch image, before anything
	// loads it.
	dir, err := os.MkdirTemp("", "no-ca-certificates")
	if err != nil {
		panic(err)
	}
	if err := os.Setenv("SSL_CERT_FILE", filepath.Join(dir, "none.pem")); err != nil {
		panic(err)
	}
	if err := os.Setenv("SSL_CERT_DIR", dir); err != nil {
		panic(err)
	}
	code := m.Run()
	_ = os.RemoveAll(dir)
	os.Exit(code)
}

func TestVerifiesPublicCertificatesWithoutSystemRoots(t *testing.T) {
	block, _ := pem.Decode([]byte(isrgRootX1))
	if block == nil {
		t.Fatal("cannot decode the ISRG Root X1 certificate")
	}
	cert, err := x509.ParseCertificate(block.Bytes)
	if err != nil {
		t.Fatalf("cannot parse the ISRG Root X1 certificate: %v", err)
	}

	// Nil roots means the system roots, which are empty here.
	if _, err := cert.Verify(x509.VerifyOptions{}); err != nil {
		t.Fatalf("cannot verify a public certificate without system CA certificates: %v", err)
	}
}
